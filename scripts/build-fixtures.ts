/** Serialize one resumable breakpoint prefix (header + full event history). */
function evalPrefix(scenario: EvalScenario): string {
  const lines: string[] = [JSON.stringify({
    type: 'session', version: 0, id: `${scenario.name}-prefix`, createdAt: scenario.createdAt,
    cwd: '/workspace', delegationDepth: 0,
  })]
  const events: { type: string; data: unknown; surfaceOp?: 'append' }[] = [
    { type: 'turn/start', data: { turn: 1 } },
    {
      type: 'user/message',
      data: {
        content: [{ type: 'text', text: scenario.task }],
        source: { kind: 'user' },
        role: 'user',
        id: 'prefix-task-message',
      },
      surfaceOp: 'append',
    },
    { type: 'step/start', data: { turn: 1, step: 1 } },
    {
      type: 'assistant/message',
      data: {
        turn: 1,
        step: 1,
        message: {
          role: 'assistant',
          content: [{ type: 'tool-call', id: scenario.callId, name: scenario.tool, arguments: scenario.rawArguments }],
          source: { kind: 'model', provider: 'deepseek-official', model: 'deepseek-v4-flash' },
          id: 'prefix-assistant-message',
        },
        usage: { inputTokens: 400, outputTokens: scenario.rawArguments.length, cacheReadTokens: 0, reasoningTokens: 0 },
      },
      surfaceOp: 'append',
    },
    { type: 'tool/call', data: { turn: 1, step: 1, callId: scenario.callId, name: scenario.tool, arguments: scenario.rawArguments } },
    {
      type: 'tool/result',
      data: {
        turn: 1,
        step: 1,
        message: {
          source: { kind: 'tool', callId: scenario.callId },
          content: [{
            type: 'tool-result',
            toolCallId: scenario.callId,
            content: [{ type: 'text', text: scenario.errorText }],
            isError: true,
          }],
          role: 'user',
          id: 'prefix-tool-result-message',
        },
      },
      surfaceOp: 'append',
    },
    { type: 'step/end', data: { turn: 1, step: 1 } },
  ]
  let seq = 0
  let time = scenario.createdAt
  for (const event of events) {
    time += 1
    lines.push(JSON.stringify({
      type: event.type, seq: seq++, time, data: event.data,
      ...event.surfaceOp === undefined ? {} : { surfaceOp: event.surfaceOp },
    }))
  }
  return `${lines.join('\n')}\n`
}

export function buildEvalFixtures(root = EVAL_FIXTURES): string[] {
  const written: string[] = []
  for (const scenario of EVAL_SCENARIOS) {
    const dir = join(root, scenario.name)
    mkdirSync(dir, { recursive: true })
    // The committed prefix ends at the breakpoint (the OFF-arm baseline).
    // The ON arm's notice user/message is appended by the eval driver at
    // load time (its text carries the machine-specific path token); the
    // notice text itself is committed in scenario.json.
    writeFileSync(join(dir, 'session-prefix.jsonl'), evalPrefix(scenario))
    written.push(join(dir, 'session-prefix.jsonl'))
    writeFileSync(join(dir, 'scenario.json'), `${JSON.stringify({
      name: scenario.name,
      mode: scenario.mode,
      callId: scenario.callId,
      tool: scenario.tool,
      continuation: scenario.continuation,
      notice: scenario.notice,
    }, null, 2)}\n`)
    written.push(join(dir, 'scenario.json'))
  }
  return written
}

// Direct execution: regenerate the committed fixture corpus.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const written = [...buildReplayFixtures(), ...buildEvalFixtures()]
  for (const file of written) {
    console.log(`wrote ${file}`)
  }
}
