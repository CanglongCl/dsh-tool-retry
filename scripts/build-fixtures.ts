        + 'spec:\n  replicas: {replicas}\n  selector:\n    matchLabels:\n'
        + '      app: {name}\n  template:\n    metadata:\n      labels:\n'
        + '        app: {name}\n    spec:\n      containers:\n      - name: app\n'
