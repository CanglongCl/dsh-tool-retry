export function buildReplayFixtures(root = FIXTURES): string[] {
  const written: string[] = []
  for (const scenario of SCENARIOS) {
    const dir = join(root, scenario.name)
    mkdirSync(dir, { recursive: true })
    const jsonl = sessionLog(scenario.name, scenario.createdAt, [scenario.breakpoint])
    writeFileSync(join(dir, 'session.jsonl'), jsonl)
    written.push(join(dir, 'session.jsonl'))
    // Bare-array replacement script: the breakpoint round followed by the
    // post-break steps (see the module doc for why not { patches }).
    const override = [scriptEntry(scenario.breakpoint), ...scenario.retry.map(scriptEntry)]
    writeFileSync(join(dir, 'replay.override.json'), `${JSON.stringify(override, null, 2)}\n`)
    written.push(join(dir, 'replay.override.json'))
  }
  return written
}

